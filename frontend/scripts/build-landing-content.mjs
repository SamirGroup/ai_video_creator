/**
 * Builds public/mw/content.js from the per-locale JSON in public/mw/content/.
 *
 * The landing page is a prebuilt, minified bundle (see public/mw/), so its copy
 * cannot live in source the way the React app's does. Keeping it in JSON here
 * and generating one classic script means editing the landing never requires
 * touching minified code again, and adding a locale is dropping in a file.
 *
 * The generated script must run BEFORE the bundle's module script: it defines
 * window.__CA__, which the bundle's data objects are rewritten to read from.
 *
 * Usage: node scripts/build-landing-content.mjs
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const contentDir = join(here, '..', 'public', 'mw', 'content')
const registry = JSON.parse(
  readFileSync(join(here, '..', 'src', 'i18n', 'languages.json'), 'utf8'),
)

/** flagcdn keys on country, not language, so each locale names its flag. */
const FLAG = {
  ru: 'ru', en: 'gb', fr: 'fr', zh: 'cn', ko: 'kr', de: 'de', ar: 'sa', tr: 'tr',
  uz: 'uz', fa: 'ir', hi: 'in', ur: 'pk', ky: 'kg', kk: 'kz', tg: 'tj', tk: 'tm',
  az: 'az', ka: 'ge', es: 'es', 'ar-EG': 'eg', ha: 'ng', pt: 'pt', it: 'it',
  ja: 'jp', id: 'id', bn: 'bd', vi: 'vn', th: 'th', pl: 'pl', uk: 'ua',
}

const FALLBACK = 'en'
const BLOCKS = ['ab', 'fH', 'hH', 'AH', 'VH', 'WH', 'KH', 'integr', 'svc']

const available = new Set(
  readdirSync(contentDir).filter((f) => f.endsWith('.json')).map((f) => f.slice(0, -5)),
)
if (!available.has(FALLBACK)) throw new Error(`missing ${FALLBACK}.json`)

const reference = JSON.parse(readFileSync(join(contentDir, `${FALLBACK}.json`), 'utf8'))

/** Structural equality — a locale that drifts would crash a section at runtime. */
function shape(value) {
  if (Array.isArray(value)) return value.map(shape)
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.keys(value).sort().map((k) => [k, shape(value[k])]))
  }
  return 'S'
}
const referenceShape = JSON.stringify(shape(reference))

const locales = registry.map((l) => l.code).filter((c) => available.has(c))
const missing = registry.map((l) => l.code).filter((c) => !available.has(c))

const byBlock = Object.fromEntries(BLOCKS.map((b) => [b, {}]))
for (const code of locales) {
  const doc = JSON.parse(readFileSync(join(contentDir, `${code}.json`), 'utf8'))
  if (JSON.stringify(shape(doc)) !== referenceShape) {
    throw new Error(`${code}.json does not match the shape of ${FALLBACK}.json`)
  }
  for (const block of BLOCKS) byBlock[block][code] = doc[block]
}

const langs = registry
  .filter((l) => available.has(l.code))
  .map((l) => ({
    code: l.code,
    name: l.native_name,
    dir: l.direction === 'rtl' ? 'rtl' : 'ltr',
    flagUrl: `https://flagcdn.com/w40/${FLAG[l.code] || 'gb'}.png`,
  }))

const script = `/* Generated by scripts/build-landing-content.mjs — do not edit by hand.
   Landing copy for ${locales.length} locales. Loaded as a classic script before the
   bundle, which reads its data objects off window.__CA__. */
(function () {
  var FALLBACK = ${JSON.stringify(FALLBACK)};
  var STORE = 'ai-youtuber-locale';
  var LANGS = ${JSON.stringify(langs)};
  var DATA = ${JSON.stringify(byBlock)};

  var byCode = {};
  for (var i = 0; i < LANGS.length; i++) byCode[LANGS[i].code] = LANGS[i];

  /* Any locale a section asks for that is somehow absent resolves to the
     fallback rather than throwing: a missing key must never blank the page. */
  function withFallback(map) {
    return new Proxy(map, {
      get: function (target, key) {
        if (typeof key !== 'string') return target[key];
        return key in target ? target[key] : target[FALLBACK];
      },
      has: function () { return true; },
    });
  }

  var blocks = {};
  for (var name in DATA) blocks[name] = withFallback(DATA[name]);

  window.__CA__ = {
    langs: LANGS,
    fallback: FALLBACK,

    block: function (name) { return blocks[name]; },

    /* Icons are React components living in the bundle, so they stay there and
       are merged back onto each item by position. */
    blockWithIcons: function (name, icons, key) {
      var source = DATA[name], out = {};
      for (var code in source) {
        var value = source[code];
        var items = value[key].map(function (item, index) {
          return Object.assign({}, item, { icon: icons[index] });
        });
        out[code] = Object.assign({}, value, Object.fromEntries([[key, items]]));
      }
      return withFallback(out);
    },

    initialLang: function () {
      try {
        var stored = localStorage.getItem(STORE);
        if (stored && byCode[stored]) return stored;
      } catch (e) { /* storage can be blocked; fall through */ }
      var nav = (navigator.languages || [navigator.language || '']).slice();
      for (var i = 0; i < nav.length; i++) {
        var tag = String(nav[i]);
        if (byCode[tag]) return tag;
        var base = tag.split('-')[0];
        if (byCode[base]) return base;
      }
      return FALLBACK;
    },

    applyLang: function (code) {
      var entry = byCode[code] || byCode[FALLBACK];
      var root = document.documentElement;
      root.setAttribute('lang', entry.code);
      root.setAttribute('dir', entry.dir);
      try { localStorage.setItem(STORE, entry.code); } catch (e) { /* optional */ }
    },
  };
})();
`

writeFileSync(join(here, '..', 'public', 'mw', 'content.js'), script)

console.log(`locales : ${locales.length}/${registry.length}`)
if (missing.length) console.log(`missing : ${missing.join(', ')}`)
console.log(`blocks  : ${BLOCKS.join(', ')}`)
console.log(`written : public/mw/content.js (${(script.length / 1024).toFixed(0)} kB)`)
